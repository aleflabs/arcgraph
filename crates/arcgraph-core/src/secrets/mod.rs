/// The provider trait every secrets backend implements.
///
/// All methods are synchronous and `&self`-callable so the trait is
/// `Send + Sync` and embeddable as `Arc<dyn SecretsProvider>` in
/// long-lived structs (WAL encryption config, page-store encryption
/// adapter, connector credential store).
///
/// **Key namespace convention** (v1.0-α): callers prefix keys with a
/// per-subsystem namespace + per-tenant scope + version suffix —
/// e.g., `arcgraph.wal.encryption_key.v1`,
/// `connector.credentials.t<tenant>.v<version>`. The provider treats
/// the entire string as opaque; the convention is enforced at the
/// consumer (see `arcgraph-storage::encryption::wal::WalEncryption`).
///
/// **Threading contract**: methods MAY block on the underlying
/// keyring / D-Bus / file IO. Callers SHOULD invoke from a non-hot-
/// path thread (typical: at startup + at rotation events).
pub trait SecretsProvider: Send + Sync + std::fmt::Debug {
    /// Retrieve the secret bound to `key`. Returns
    /// [`SecretsError::NotFound`] if no such binding exists.
    fn get(&self, key: &str) -> Result<SecretValue, SecretsError>;

    /// Bind `value` to `key`, overwriting any prior value.
    fn set(&self, key: &str, value: SecretValue) -> Result<(), SecretsError>;

    /// Rotate the key bound to `key`: generate a fresh 32-byte value,
    /// increment the per-key version counter, and store the new value
    /// at `key.v<new_version>`. Returns the new [`KeyVersion`].
    ///
    /// Historical versions remain accessible at `key.v<N>` for N <
    /// new_version — the provider does NOT delete prior versions
    /// (operator policy decides retention). Callers that need
    /// version-aware reads (e.g., per-record WAL decryption) read
    /// `key.v<N>` explicitly via [`Self::get`].
    fn rotate(&self, key: &str) -> Result<KeyVersion, SecretsError>;

    /// Delete the secret bound to `key`. Returns
    /// [`SecretsError::NotFound`] if no such binding exists; idempotent
    /// re-delete is the caller's responsibility (wrap with a
    /// `match err { NotFound => Ok(()), other => other }` if
    /// idempotency is needed).
    fn delete(&self, key: &str) -> Result<(), SecretsError>;
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Compile-time pin: `dyn SecretsProvider` is object-safe + Send +
    /// Sync. Without `Send + Sync` the WAL encryption config (which
    /// holds an `Arc<dyn SecretsProvider>`) would not compile against
    /// the writer thread's `move` semantics.
    #[test]
    fn provider_is_object_safe_and_send_sync() {
        fn assert_object_safe(_: &dyn SecretsProvider) {}
        fn assert_send_sync<T: Send + Sync>() {}
        let p = EnvSecretsProvider::with_prefix("test_object_safe");
        assert_object_safe(&p);
        assert_send_sync::<EnvSecretsProvider>();
    }
}
