//! Secrets provider abstraction (W20β-3 / ADR-052).
//!
//! `arcgraph-core` ships a `SecretsProvider` trait + two
//! implementations:
//!
//! - `OsKeyringProvider` — production default; wraps the `keyring`
//!   crate's macOS Keychain / Windows Credential Manager / Linux
//!   Secret Service backends. Feature-gated behind `os-keyring` so
//!   headless CI environments build without D-Bus / Secret Service.
//! - [`EnvSecretsProvider`] — development-only; reads from process env
//!   vars (`ARCGRAPH_SECRET_<KEY>`). Construction emits a
//!   `tracing::warn!` tagged `unsafe_for_prod=true` so operators see
//!   the danger in startup logs (pinned by tests).
//!
//! Full KMS providers (HashiCorp Vault, AWS KMS, GCP KMS, Azure Key
//! Vault) are **deferred to v1.2** per sister ADR-051. The trait
//! surface is stable at v1.0; new impls add via the `dyn` interface.
//!
//! ## Threat model
//!
//! See ADR-052 §"Context" for the full threat model. In short: cold
//! disk theft, backup leakage, and snapshot exfiltration. Chosen-
//! plaintext / chosen-ciphertext active attackers are NOT in the v1.0
//! threat model (those land at v1.2 with HSM / KMS lift per ADR-051).
//!
//! ## Why a 32-byte fixed-width [`SecretValue`]
//!
//! Every consumer of the provider in v1.0-α is an AES-256 key (32
//! bytes). Fixing the width at the trait surface simplifies key
//! rotation (`rotate()` returns a new 32-byte key generated by the
//! provider; no caller-side size negotiation), eliminates variable-
//! length attack surface (no length-extension or oracle attacks on
//! the provider's storage layer), and matches the FIPS-140-3
//! candidate AES-256-GCM requirement. v1.1+ consumers (e.g.,
//! per-tenant Curve25519 keys for signing) will need a
//! variable-width sibling type; the trait MAY add a sibling method
//! at v1.1 — adding methods to a trait is a breaking change but the
//! existing `get` / `set` / `rotate` / `delete` shape stays.
//!
//! ## See also
//!
//! - `arcgraph-storage::encryption` — the production consumer of this trait
//! - protocol adapters — per-tenant credential storage

